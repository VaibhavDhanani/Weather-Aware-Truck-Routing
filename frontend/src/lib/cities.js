export function findCity(query) {
  const q = query.trim().toLowerCase()
  if (!q) return null
  return (
    CITIES.find((c) => c.name.toLowerCase() === q) ??
    CITIES.find((c) => c.name.toLowerCase().startsWith(q))
  )
}
